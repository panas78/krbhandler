#!/bin/bash
# ══════════════════════════════════════════════════════════════════════════════
# krbctl installer
#
#   ./install.sh              install for the current user (~/.local)
#   ./install.sh --uninstall  remove everything it put there
#   ./install.sh --no-autostart
#
# The GUI stack is installed from the distro rather than pip: PyGObject, GTK4,
# libadwaita, libsecret and pycairo ship typelibs that must match the system
# libraries. A pip wheel of PyGObject in a venv routinely cannot see them.
# ══════════════════════════════════════════════════════════════════════════════
set -euo pipefail

SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PREFIX="${PREFIX:-$HOME/.local}"
APPS="$PREFIX/share/applications"
ICONS="$PREFIX/share/icons/hicolor"
BINDIR="$PREFIX/bin"
AUTOSTART="${XDG_CONFIG_HOME:-$HOME/.config}/autostart"
METADATA="$PREFIX/share/metainfo"

DO_AUTOSTART=1
DO_UNINSTALL=0
for arg in "$@"; do
  case "$arg" in
    --uninstall) DO_UNINSTALL=1 ;;
    --no-autostart) DO_AUTOSTART=0 ;;
    -h|--help)
      sed -n '2,12p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
      exit 0 ;;
    *) echo "Unknown option: $arg" >&2; exit 2 ;;
  esac
done

say() { printf '\033[1m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[33m[warn]\033[0m %s\n' "$*"; }

# ── uninstall ────────────────────────────────────────────────────────────────
if [ "$DO_UNINSTALL" -eq 1 ]; then
  say "Removing krbctl from $PREFIX"
  rm -f "$APPS/io.github.pan.Krbctl.desktop" "$AUTOSTART/krbctl-tray.desktop"
  rm -f "$METADATA/io.github.pan.Krbctl.metainfo.xml"
  rm -rf "$PREFIX/share/krbctl"
  rm -f "$BINDIR/krbctl"
  # Remove every size of the icon set that was installed.
  for size in 16 22 24 32 48 64 128 256 512; do
    rm -f "$ICONS/${size}x${size}/apps/krbctl.png"
    rmdir "$ICONS/${size}x${size}/apps" "$ICONS/${size}x${size}" 2>/dev/null || true
  done
  command -v gtk-update-icon-cache >/dev/null && gtk-update-icon-cache -qtf "$ICONS" 2>/dev/null || true
  command -v update-desktop-database >/dev/null && update-desktop-database "$APPS" 2>/dev/null || true
  say "Left in place: ~/.config/krbctl/accounts.json (delete it by hand if you want a clean slate)"
  exit 0
fi

# ── dependencies ─────────────────────────────────────────────────────────────
have_python_gui() {
  /usr/bin/python3 - <<'PY' >/dev/null 2>&1
import gi
gi.require_version("Gtk", "4.0")
gi.require_version("Adw", "1")
from gi.repository import Gtk, Adw
import cairo
PY
}

if ! have_python_gui; then
  say "Installing the GTK4 / libadwaita / libsecret stack"
  if command -v dnf >/dev/null; then
    sudo dnf install -y python3-gobject gtk4 libadwaita python3-cairo \
      libsecret krb5-workstation desktop-file-utils
  elif command -v apt-get >/dev/null; then
    sudo apt-get update
    sudo apt-get install -y python3-gi gir1.2-gtk-4.0 gir1.2-adw-1 \
      python3-cairo libsecret-1-0 krb5-user desktop-file-utils
  elif command -v pacman >/dev/null; then
    sudo pacman -S --needed --noconfirm python-gobject gtk4 libadwaita \
      python-cairo libsecret krb5
  else
    warn "Unknown package manager — install PyGObject, GTK4, libadwaita,"
    warn "pycairo and krb5-workstation yourself, then re-run this script."
    exit 1
  fi
else
  say "GUI dependencies already present"
fi

if ! command -v kinit >/dev/null; then
  warn "kinit not found — install krb5-workstation (Fedora) or krb5-user (Debian)"
fi

# ── payload ──────────────────────────────────────────────────────────────────
say "Installing the application into $PREFIX/share/krbctl"
rm -rf "$PREFIX/share/krbctl"
mkdir -p "$PREFIX/share/krbctl"
cp -a "$SRC_DIR/krbctl" "$PREFIX/share/krbctl/krbctl"
# The tray icon is drawn at runtime, so the payload needs no image of its own.
# The launcher icon set goes into the icon theme below instead, so drop the copy
# that comes along with data/ to avoid installing it twice.
rm -rf "$PREFIX/share/krbctl/krbctl/__pycache__"
cp -a "$SRC_DIR/data" "$PREFIX/share/krbctl/data"
rm -rf "$PREFIX/share/krbctl/data/icons"
# The .in templates are build inputs; installed entries are already generated.
rm -f "$PREFIX/share/krbctl/data"/*.desktop.in

mkdir -p "$BINDIR"
cat > "$BINDIR/krbctl" <<EOF
#!/bin/sh
# Generated by krbctl install.sh — runs the app with the system interpreter,
# because that is the one with the GTK/libsecret typelibs. -B keeps the
# installed tree free of __pycache__ (which would otherwise turn stale on the
# next upgrade).
exec /usr/bin/python3 -B -c 'import sys; sys.path.insert(0, "$PREFIX/share/krbctl"); from krbctl.cli import main; sys.exit(main())' "\$@"
EOF
chmod +x "$BINDIR/krbctl"

# ── desktop integration ──────────────────────────────────────────────────────
say "Installing icon set"
mkdir -p "$ICONS"
installed_icons=0
for size in 16 22 24 32 48 64 128 256 512; do
  src_icon="$SRC_DIR/data/icons/hicolor/${size}x${size}/apps/krbctl.png"
  [ -f "$src_icon" ] || continue
  mkdir -p "$ICONS/${size}x${size}/apps"
  cp -f "$src_icon" "$ICONS/${size}x${size}/apps/krbctl.png"
  installed_icons=$((installed_icons + 1))
done
if [ "$installed_icons" -eq 0 ]; then
  warn "No icon PNGs found in data/icons/hicolor — the icon set is missing from the source tree"
else
  echo "    $installed_icons sizes"
fi

say "Creating desktop entries"
mkdir -p "$APPS" "$METADATA"

# The entries are templates in data/ so there is one place to edit each; the
# only thing install.sh substitutes is where krbctl actually landed.
install_template() {
  local template="$1" target="$2"
  sed "s|@BINDIR@|$BINDIR|g" "$template" > "$target"
  chmod 644 "$target"
}

install_template "$SRC_DIR/data/krbctl.desktop.in" "$APPS/io.github.pan.Krbctl.desktop"

cp -f "$SRC_DIR/data/io.github.pan.Krbctl.metainfo.xml" "$METADATA/"

# The autostart entry is generated by the app itself, so there is one definition
# of it and the GUI switch, `krbctl autostart on|off` and this script can never
# disagree. Do it with the freshly installed wrapper, not the source tree.
if [ "$DO_AUTOSTART" -eq 1 ]; then
  say "Enabling the tray on login"
  "$BINDIR/krbctl" autostart on >/dev/null
else
  "$BINDIR/krbctl" autostart off >/dev/null 2>&1 || true
fi

# Refresh caches; failures here are cosmetic, never fatal.
command -v update-desktop-database >/dev/null && update-desktop-database "$APPS" 2>/dev/null || true
command -v gtk-update-icon-cache >/dev/null && gtk-update-icon-cache -qtf "$ICONS" 2>/dev/null || true

# Validate what we just wrote — a malformed .desktop file appears in no menu at
# all, silently, which is exactly the kind of failure worth catching here.
if command -v desktop-file-validate >/dev/null; then
  say "Validating desktop entries"
  for f in "$APPS/io.github.pan.Krbctl.desktop" "$AUTOSTART/krbctl-tray.desktop"; do
    [ -f "$f" ] || continue
    if desktop-file-validate "$f"; then
      echo "    OK  $(basename "$f")"
    else
      warn "desktop-file-validate reported problems in $(basename "$f")"
    fi
  done
fi

# ── verify ───────────────────────────────────────────────────────────────────
say "Verifying"
PATH="$BINDIR:$PATH" krbctl doctor

cat <<EOF

 Done. Next steps:

   krbctl gui        open the window and check your account
   krbctl status     print the ticket state
   krbctl tray       run the tray icon in the foreground (it also autostarts)

 The app auto-detects an existing keytab, so a machine that already renews
 with kinit needs no configuration at all.
EOF
