#!/bin/bash
# ══════════════════════════════════════════════════════════════════════════════
# krbctl installer
#
#   ./install.sh              install for the current user (~/.local)
#   ./install.sh --uninstall  remove everything it put there
#   ./install.sh --no-autostart
#
# The GUI stack is installed from the distro rather than pip: PyGObject, GTK4,
# libadwaita, libsecret and pycairo ship typelibs that must match the system
# libraries. A pip wheel of PyGObject in a venv routinely cannot see them.
# ══════════════════════════════════════════════════════════════════════════════
set -euo pipefail

SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PREFIX="${PREFIX:-$HOME/.local}"
APPS="$PREFIX/share/applications"
ICONS="$PREFIX/share/icons/hicolor/scalable/apps"
BINDIR="$PREFIX/bin"
AUTOSTART="${XDG_CONFIG_HOME:-$HOME/.config}/autostart"
METADATA="$PREFIX/share/metainfo"

DO_AUTOSTART=1
DO_UNINSTALL=0
for arg in "$@"; do
  case "$arg" in
    --uninstall) DO_UNINSTALL=1 ;;
    --no-autostart) DO_AUTOSTART=0 ;;
    -h|--help)
      sed -n '2,12p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
      exit 0 ;;
    *) echo "Unknown option: $arg" >&2; exit 2 ;;
  esac
done

say() { printf '\033[1m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[33m[warn]\033[0m %s\n' "$*"; }

# ── uninstall ────────────────────────────────────────────────────────────────
if [ "$DO_UNINSTALL" -eq 1 ]; then
  say "Removing krbctl from $PREFIX"
  rm -f "$APPS/io.github.pan.Krbctl.desktop" "$AUTOSTART/krbctl-tray.desktop"
  rm -f "$ICONS/krbctl.svg"
  rm -f "$METADATA/io.github.pan.Krbctl.metainfo.xml"
  rm -rf "$PREFIX/share/krbctl"
  rm -f "$BINDIR/krbctl"
  say "Left in place: ~/.config/krbctl/accounts.json (delete it by hand if you want a clean slate)"
  exit 0
fi

# ── dependencies ─────────────────────────────────────────────────────────────
have_python_gui() {
  /usr/bin/python3 - <<'PY' >/dev/null 2>&1
import gi
gi.require_version("Gtk", "4.0")
gi.require_version("Adw", "1")
from gi.repository import Gtk, Adw
import cairo
PY
}

if ! have_python_gui; then
  say "Installing the GTK4 / libadwaita / libsecret stack"
  if command -v dnf >/dev/null; then
    sudo dnf install -y python3-gobject gtk4 libadwaita python3-cairo \
      libsecret krb5-workstation desktop-file-utils
  elif command -v apt-get >/dev/null; then
    sudo apt-get update
    sudo apt-get install -y python3-gi gir1.2-gtk-4.0 gir1.2-adw-1 \
      python3-cairo libsecret-1-0 krb5-user desktop-file-utils
  elif command -v pacman >/dev/null; then
    sudo pacman -S --needed --noconfirm python-gobject gtk4 libadwaita \
      python-cairo libsecret krb5
  else
    warn "Unknown package manager — install PyGObject, GTK4, libadwaita,"
    warn "pycairo and krb5-workstation yourself, then re-run this script."
    exit 1
  fi
else
  say "GUI dependencies already present"
fi

if ! command -v kinit >/dev/null; then
  warn "kinit not found — install krb5-workstation (Fedora) or krb5-user (Debian)"
fi

# ── payload ──────────────────────────────────────────────────────────────────
say "Installing the application into $PREFIX/share/krbctl"
rm -rf "$PREFIX/share/krbctl"
mkdir -p "$PREFIX/share/krbctl"
cp -a "$SRC_DIR/krbctl" "$PREFIX/share/krbctl/krbctl"
cp -a "$SRC_DIR/data" "$PREFIX/share/krbctl/data"

mkdir -p "$BINDIR"
cat > "$BINDIR/krbctl" <<EOF
#!/bin/sh
# Generated by krbctl install.sh — runs the app with the system interpreter,
# because that is the one with the GTK/libsecret typelibs.
exec /usr/bin/python3 -c 'import sys; sys.path.insert(0, "$PREFIX/share/krbctl"); from krbctl.cli import main; sys.exit(main())' "\$@"
EOF
chmod +x "$BINDIR/krbctl"

# ── desktop integration ──────────────────────────────────────────────────────
say "Installing desktop entry, icon and AppStream metadata"
mkdir -p "$APPS" "$ICONS" "$METADATA"
# `krbctl window` opens the window; plain `krbctl tray` is the autostart entry.
sed 's|^Exec=krbctl window|Exec=krbctl gui|' \
  "$SRC_DIR/data/io.github.pan.Krbctl.desktop" > "$APPS/io.github.pan.Krbctl.desktop"
cp -f "$SRC_DIR/data/icons/hicolor/scalable/apps/krbctl.svg" "$ICONS/krbctl.svg"
cp -f "$SRC_DIR/data/io.github.pan.Krbctl.metainfo.xml" "$METADATA/"

if [ "$DO_AUTOSTART" -eq 1 ]; then
  say "Enabling the tray on login (~/.config/autostart)"
  mkdir -p "$AUTOSTART"
  cp -f "$SRC_DIR/data/krbctl-tray.desktop" "$AUTOSTART/krbctl-tray.desktop"
else
  rm -f "$AUTOSTART/krbctl-tray.desktop"
fi

# Refresh caches; failures here are cosmetic, never fatal.
command -v update-desktop-database >/dev/null && update-desktop-database "$APPS" 2>/dev/null || true
command -v gtk-update-icon-cache >/dev/null && gtk-update-icon-cache -qtf "$PREFIX/share/icons/hicolor" 2>/dev/null || true

# ── verify ───────────────────────────────────────────────────────────────────
say "Verifying"
PATH="$BINDIR:$PATH" krbctl doctor

cat <<EOF

 Done. Next steps:

   krbctl gui        open the window and check your account
   krbctl status     print the ticket state
   krbctl tray       run the tray icon in the foreground (it also autostarts)

 The app auto-detects an existing keytab, so a machine that already renews
 with kinit needs no configuration at all.
EOF
